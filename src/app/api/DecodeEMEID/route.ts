/**
 * @file app/api/DecodeEMEID/route.ts
 * @description Decrypts the AES-256-CBC EMEID token appended to every Adobe
 * Campaign tracked link click.
 *
 * Adobe Campaign automatically appends EMEID and CUHID to the landing-page
 * URL on every click, e.g.:
 *
 *   GET /ftr-forms/api/DecodeEMEID
 *       ?EMEID=180e0b4d…bc85
 *       &CUHID=ce657692…968f
 *
 * The endpoint validates the query parameters with Zod, decrypts EMEID using
 * AES-256-CBC (key/IV from environment variables), and returns the plaintext.
 *
 * @openapi
 * /ftr-forms/api/DecodeEMEID:
 *   get:
 *     summary: Decrypt an Adobe Campaign EMEID token
 *     description: >
 *       Accepts the EMEID (and optionally CUHID) query-string parameters that
 *       Adobe Campaign appends to every tracked link click. Decrypts the EMEID
 *       using AES-256-CBC and returns the plaintext (typically an email address
 *       or subscriber identifier).
 *     tags: [Adobe Campaign]
 *     parameters:
 *       - in: query
 *         name: EMEID
 *         required: true
 *         schema:
 *           type: string
 *           example: "180e0b4dbbaef29fa3e846656da933a7239bb7572f7611ac6e8722972421bc85"
 *         description: >
 *           Hex-encoded AES-256-CBC ciphertext (with embedded 16-byte IV
 *           prepended) generated by Adobe Campaign.
 *       - in: query
 *         name: CUHID
 *         required: false
 *         schema:
 *           type: string
 *           example: "ce657692ae19f328a459aa07b327136e665b02b9fb29f4768cede5ffb26e968f"
 *         description: Contact Unique Hash ID — passed through for logging purposes.
 *     responses:
 *       200:
 *         description: EMEID decoded successfully
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 data:
 *                   type: object
 *                   properties:
 *                     decoded:
 *                       type: string
 *                       example: "subscriber@example.com"
 *                     cuhid:
 *                       type: string
 *                       nullable: true
 *                       example: "ce657692ae19f328a459aa07b327136e665b02b9fb29f4768cede5ffb26e968f"
 *       400:
 *         description: Validation failed — EMEID is missing or not valid hex
 *       500:
 *         description: Decryption failed or server misconfiguration
 */

import type { NextRequest } from "next/server";
import { withErrorHandler } from "@/utils/withErrorHandler";
import { successResponse, errorResponse } from "@/utils/response";
import { DecodeEMEIDSchema } from "@/utils/emeidValidation";
import { decodeEMEID } from "@/utils/emeidDecryption";
import { maskEmail } from "@/logger";
import logger from "@/logger";
import { HTTP_STATUS } from "@/constants";

export const dynamic = "force-dynamic";

// ---------------------------------------------------------------------------
// GET /ftr-forms/api/DecodeEMEID
// ---------------------------------------------------------------------------
export const GET = withErrorHandler(async (request: NextRequest) => {
  const { searchParams } = new URL(request.url);

  // URLSearchParams decodes '+' as a space (application/x-www-form-urlencoded).
  // Base64 strings may contain '+', so we normalise spaces back to '+' here.
  // Hex-only values are unaffected (they never contain spaces or '+').
  const normalise = (v: string | null): string | undefined =>
    v == null ? undefined : v.replace(/ /g, "+");

  const rawQuery = {
    EMEID: normalise(searchParams.get("EMEID")),
    CUHID: normalise(searchParams.get("CUHID")),
  };

  // ── 1. Validate ────────────────────────────────────────────────────────────
  const parsed = DecodeEMEIDSchema.safeParse(rawQuery);
  if (!parsed.success) {
    return errorResponse(
      "Validation failed",
      HTTP_STATUS.BAD_REQUEST,
      parsed.error.flatten().fieldErrors as Record<string, string[]>,
    );
  }

  const { EMEID, CUHID } = parsed.data;

  // ── 2. Decrypt ─────────────────────────────────────────────────────────────
  let decoded: string;
  try {
    decoded = decodeEMEID(EMEID);
  } catch (err) {
    const message = err instanceof Error ? err.message : "Decryption error";
    logger.error("EMEID decryption failed", {
      emeidLength: EMEID.length,
      error: message,
    });
    return errorResponse(message, HTTP_STATUS.INTERNAL_SERVER_ERROR);
  }

  // ── 3. Log (PII-safe) ──────────────────────────────────────────────────────
  // Mask the decoded value if it looks like an email; otherwise truncate.
  const maskedDecoded = decoded.includes("@")
    ? maskEmail(decoded)
    : `${decoded.slice(0, 4)}…`;

  logger.info("EMEID decoded successfully", {
    decoded: maskedDecoded,
    cuhid: CUHID ?? null,
  });

  // ── 4. Respond ─────────────────────────────────────────────────────────────
  return successResponse({
    decoded,
    cuhid: CUHID ?? null,
  });
});
